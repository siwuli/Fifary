// 没翻译的文案原样显示中文，不会变成空白
fun S(zh: String): String = if (Lang.en) Lang.dict[zh] ?: zh else zh

fun resolveEnglish(mode: AppLang): Boolean = when (mode) {
    AppLang.EN -> true
    AppLang.ZH -> false
    AppLang.SYSTEM -> Locale.getDefault().language.equals("en", true)
}

fun applyLang(mode: AppLang) {
    Lang.en = resolveEnglish(mode)
}
